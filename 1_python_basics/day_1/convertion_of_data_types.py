#converting int data type to other data types
a=5
print(a) #5
print(type(a))#<type 'int'>
print(type(float(a)))#<type 'float'>
print(type(str(a)))#<type 'str'>
print(type(bool(a)))#<type 'bool'>
print(type(complex(a)))#<type 'complex'>
